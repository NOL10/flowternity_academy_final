import { jsPDF } from 'jspdf';
import { getPerformanceClassification, getPerformanceAdvice, PERFORMANCE_CLASSIFICATIONS } from './performance-advice';

// Generate PDF report with scores and coaching advice
export async function generatePerformanceReportPDF(playerName, sport, metrics, scores, generatedDate) {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  let yPosition = margin;
  
  // Helper: add page break if needed
  const ensureSpace = (neededHeight) => {
    if (yPosition + neededHeight > pageHeight - 20) {
      doc.addPage();
      yPosition = margin;
    }
  };
  
  // HEADER
  doc.setFillColor(31, 41, 55); // dark slate
  doc.rect(0, 0, pageWidth, 40, 'F');
  
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(24);
  doc.setTextColor(212, 255, 36); // lime
  doc.text('BASKETBALL PERFORMANCE REPORT', margin, 20);
  
  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text(`${sport.toUpperCase()} • ${generatedDate}`, margin, 30);
  
  yPosition = 50;
  
  // PLAYER INFO
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(50, 50, 50);
  doc.text(playerName, margin, yPosition);
  
  yPosition += 10;
  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 100, 100);
  doc.text(`Assessment Date: ${generatedDate}`, margin, yPosition);
  doc.text(`Total Metrics Evaluated: ${metrics.length}`, pageWidth - 70, yPosition);
  
  yPosition += 15;
  
  // Calculate averages
  const validScores = scores.filter(s => s != null);
  const averageScore = validScores.length > 0 
    ? (validScores.reduce((a, b) => a + b, 0) / validScores.length).toFixed(1)
    : '—';
  
  // Summary stats
  const stats = {
    EXCELLENT: scores.filter(s => s >= 9).length,
    GOOD: scores.filter(s => s >= 7 && s < 9).length,
    DEVELOPING: scores.filter(s => s >= 5 && s < 7).length,
    NEEDS_IMPROVEMENT: scores.filter(s => s >= 3 && s < 5).length,
    CRITICAL: scores.filter(s => s < 3).length,
  };
  
  doc.setFillColor(240, 240, 240);
  doc.rect(margin, yPosition, pageWidth - 2 * margin, 20, 'F');
  
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(50, 50, 50);
  doc.text('PERFORMANCE SUMMARY', margin + 5, yPosition + 7);
  
  doc.setFont('Helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(80, 80, 80);
  
  const summaryX = margin + 5;
  const colWidth = (pageWidth - 2 * margin - 10) / 5;
  
  Object.entries(stats).forEach(([ classification, count ], idx) => {
    const label = PERFORMANCE_CLASSIFICATIONS[classification].label;
    doc.text(`${label}: ${count}`, summaryX + idx * colWidth, yPosition + 14);
  });
  
  doc.text(`Overall Average: ${averageScore}/10`, margin + 5, yPosition + 18);
  
  yPosition += 30;
  
  // METRICS DETAIL SECTION
  doc.setFont('Helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(31, 41, 55);
  doc.text('DETAILED PERFORMANCE ANALYSIS', margin, yPosition);
  
  yPosition += 12;
  
  // Process each metric with score and advice
  metrics.forEach((metric, idx) => {
    const score = scores[idx];
    if (score == null) return; // Skip metrics without scores
    
    ensureSpace(50); // Ensure enough space for metric block
    
    const classification = getPerformanceClassification(score);
    const classData = PERFORMANCE_CLASSIFICATIONS[classification];
    const advice = getPerformanceAdvice(metric.key, score);
    
    // Metric header with colored background
    doc.setFillColor(...hexToRgb(classData.color));
    doc.rect(margin, yPosition, pageWidth - 2 * margin, 8, 'F');
    
    doc.setFont('Helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(255, 255, 255);
    doc.text(metric.label.toUpperCase(), margin + 3, yPosition + 6);
    
    // Score and classification
    doc.setFont('Helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(50, 50, 50);
    
    yPosition += 12;
    doc.text(`Score: ${score.toFixed(1)}/10`, margin + 3, yPosition);
    doc.text(`Classification: ${classData.label}`, margin + 60, yPosition);
    
    yPosition += 8;
    
    // Advice section
    if (advice) {
      doc.setFillColor(248, 248, 248);
      doc.rect(margin, yPosition - 1, pageWidth - 2 * margin, 1, 'F');
      
      doc.setFont('Helvetica', 'italic');
      doc.setFontSize(8.5);
      doc.setTextColor(60, 60, 60);
      
      // Word wrap advice text
      const wrappedAdvice = doc.splitTextToSize(advice, pageWidth - 2 * margin - 6);
      doc.text(wrappedAdvice, margin + 3, yPosition + 3);
      
      yPosition += wrappedAdvice.length * 4.5 + 8;
    } else {
      yPosition += 6;
    }
  });
  
  // FOOTER
  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text(
    `Generated by Flowternity Academy • ${new Date().toLocaleDateString('en-IN')} ${new Date().toLocaleTimeString('en-IN')}`,
    margin,
    pageHeight - 10
  );
  
  return doc;
}

// Utility: Convert hex to RGB
function hexToRgb(hex) {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  return result ? [
    parseInt(result[1], 16),
    parseInt(result[2], 16),
    parseInt(result[3], 16)
  ] : [0, 0, 0];
}
